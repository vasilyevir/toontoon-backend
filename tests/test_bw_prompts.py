"""Чёрно-белый раздел обязан просить чёрно-белое.

Это сторож против ровно той ошибки, которую я сделал руками. Промпт
`white_suit` просил монохром последним словом; я перенёс его в общий якорь
раздела, якорь оказался хуже (`spotlight` вышел цветной иллюстрацией) и был
откачен — а слова в промпт вернуть забыли. Стиль остался единственным в
разделе без указания на чёрно-белое и поехал в цвете. Заметил это человек на
своём телефоне, а не тест.

Проверка дешёвая и тупая нарочно: она не судит о качестве кадра, а только
следит, что просьба не потерялась. Такие пропажи и бывают тихими — каталог
собирается, импорт молчит, тесты зелёные, и узнаёшь через неделю от того, кто
заплатил монеты.

    PYTHONPATH=. .venv/bin/python -m pytest tests/test_bw_prompts.py -q
"""
from __future__ import annotations

import pathlib

import pytest

РАЗДЕЛ = pathlib.Path("content/styles/black_and_white")

# Так это сказано у всех карточек раздела. Не регулярка с вариантами: разнобой
# в формулировках здесь сам по себе повод посмотреть глазами.
ПРОСЬБА = "monochrome black and white"

СТИЛИ = sorted(p.parent.name for p in РАЗДЕЛ.glob("*/prompt.md"))


def сцена(слаг: str) -> str:
    """Только то, что уходит в модель: после разделителя `---`."""
    текст = (РАЗДЕЛ / слаг / "prompt.md").read_text()
    return текст.split("\n---\n", 1)[-1].strip()


def test_раздел_на_месте():
    assert СТИЛИ, "не нашлось ни одного стиля — проверка бессмысленна"


@pytest.mark.parametrize("слаг", СТИЛИ)
def test_каждый_просит_монохром(слаг):
    assert ПРОСЬБА in сцена(слаг), (
        f"«{слаг}» ничего не говорит про чёрно-белое — кадр выйдет цветным"
    )


@pytest.mark.parametrize("слаг", СТИЛИ)
def test_просьба_не_отменяется_запретом(слаг):
    """«no colour» и подобное читается как правка готовой картинки.

    На fal такие обороты давали прямые отказы: 0 из 6 против 6 из 6 после
    смягчения. Просить надо утвердительно.
    """
    низом = сцена(слаг).lower()
    for запрет in ("no colour", "no color", "not colour", "not color", "without colour"):
        assert запрет not in низом, f"«{слаг}» просит убрать цвет запретом: {запрет}"
