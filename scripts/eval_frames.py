#!/usr/bin/env python
"""Замер кадров: тот ли человек, та ли техника, есть ли заказанные слова.

    ./run-local.sh &                       # харнесс ходит по HTTP, как приложение
    PYTHONPATH=. .venv/bin/python scripts/eval_frames.py --faces ~/faces
    PYTHONPATH=. .venv/bin/python scripts/eval_frames.py --faces ~/faces \\
        --cases drawn-anime,poster-name --repeats 2

Зачем. Кадр ломается молча: ошибки нет, исключения нет, а человек получает
фотографию вместо рисунка, себя в шапке, которую не просил, или постер без
единственного слова, ради которого он его заказывал. Такие поломки мы ловили
глазами по одной, и каждая жила в продукте ровно до следующей жалобы.

Замер отвечает на три вопроса, и на все три — числом:

    сходство  — тот ли это человек (0–10, судит зрение по опорному снимку);
    техника   — рисунок это или фотография (то, что заказывали?);
    буквы     — набрано ли слово, которое человек назвал, и не набрано ли
                лишнее там, где слов не было.

Плюс время и цена: они приходят от исполнителя даром, а решают не меньше.

Ходим по HTTP на локальный сервер, а не зовём функции напрямую: мерить надо
путь целиком — сборку промпта, выбор исполнителя, проверку результата и повтор.
Половина найденных бед жила именно в стыках, а не внутри функций.

Порог здесь не «упало/прошло»: на двенадцати кадрах это враньё. Смысл в
сравнении с прошлым прогоном — «сходство было 0.7, стало 0.4» видно сразу, и
это регрессия, даже если абсолютные числа спорные.

Результат складывается в `docs/research/runs/_frames/<метка>/` рядом с прошлыми
замерами: кадры и `run.json`, сводка печатается в терминал.

Лица берутся из папки, которую указывают ключом `--faces`, и в репозиторий не
кладутся: это чьё-то лицо, а не тестовые данные.
"""
