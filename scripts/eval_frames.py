# Судья по форме VIEScore: балл и обоснование, ответ строго JSON.
#
# Обоснование обязательно, и не для красоты: по нему видно, когда судья прав
# случайно. «10, потому что борода и глаза те же» и «10, потому что человек
# похож» — разные ответы, и второй повод не верить числу.
_JUDGE_SYSTEM = (
    "You are shown two pictures: first the reference photograph of a person, "
    "then a picture generated from it. Judge only whether it is the SAME "
    "person — not the quality, not the style, not the mood. A drawing counts "
    "as the same person when the face shape, hair, build and features are "
    "recognisably theirs.\n"
    "Answer with JSON only:\n"
    '{"score": 0, "reasoning": "..."}\n'
    "score is 0 to 10: 0 — a different person, 5 — a relative-level "
    "resemblance, 10 — clearly the same person. reasoning is one short "
    "sentence naming what you compared."
)

# Вторая ось VIEScore: качество отдельно от соответствия.
#
# Первый прогон показал, зачем она нужна: замер выдал зелёный на низкой ступени
# качества, где кадры стали заметно хуже. Судья мерил сходство — человек и
# правда остался собой, просто выглядел мутнее. Оси две, и путать их нельзя.
_QUALITY_SYSTEM = (
    "You are shown one finished picture. Rate it on two axes, 0 to 10 each, "
    "judging only how it is made — not whether it matches any request.\n"
    "naturalness: 0 — obviously unnatural, wrong anatomy, melted hands, "
    "impossible light; 10 — looks like a real photograph or a properly drawn "
    "illustration of its kind.\n"
    "artifacts: 0 — heavy blur, mush, banding, warped text, watermarks, "
    "smeared detail in the face or hands; 10 — clean, sharp where it should "
    "be, no defects.\n"
    "The user says up front what kind of picture this is meant to be. Judge it "
    "by that kind: an illustration is not «unnatural» for being drawn, and a "
    "photograph is not «clean» for being smooth. Being a drawing is never an "
    "artifact.\n"
    "Every picture you see here was generated by a model, and the person in it "
    "was placed there from a reference photo. That is the job, not a defect: "
    "never lower a score for the picture «being AI» or «being a composite». "
    "Score what is visibly wrong with the craft.\n"
    "Sparse is not broken. An ink sketch leaves most of the paper empty, a "
    "poster is flat by design, a cartoon has simplified hands: none of that is "
    "a defect. Score only what is actually damaged — mangled anatomy, a "
    "smeared or melted face, unreadable mush, warped lettering, obvious "
    "seams where the person was pasted in.\n"
    "Anchor the scale: 8 is the everyday good result, 5 means one clear flaw "
    "you would notice without looking for it, 2 means the picture is unusable, "
    "0 is reserved for a ruined frame — mangled face, melted hands, unreadable "
    "mush. Do not give 0 to a picture you would be able to publish.\n"
    "Answer with JSON only:\n"
    '{"naturalness": 0, "artifacts": 0, "reasoning": "..."}\n'
    "reasoning is one short sentence naming what you looked at."
)

_ABSENT_SYSTEM = (
    "You are shown one picture. Answer with JSON only: "
    '{"present": true/false, "reasoning": "..."} — whether the thing named by '
    "the user is visible in it. Be literal: judge what you see, not what would "
    "be plausible."
)


@dataclass
class Case:
    id: str
    note: str
    body: dict
    expect: dict


@dataclass
class Outcome:
    case: str
    expect: dict = field(default_factory=dict)
    ok: bool = True
    provider: str = ""
    model: str = ""
    seconds: float = 0.0
    likeness: Optional[int] = None
    medium: str = ""
    medium_ok: Optional[bool] = None
    letters: str = ""
    letters_ok: Optional[bool] = None
    size: str = ""
    aspect_ok: Optional[bool] = None
    sharpness: float = 0.0
    naturalness: Optional[int] = None
    artifacts: Optional[int] = None
    absent_ok: Optional[bool] = None
    notes: list[str] = field(default_factory=list)
    path: str = ""

    def as_row(self) -> str:
        def mark(value: Optional[bool]) -> str:
            return "—" if value is None else ("✓" if value else "✗")

        likeness = "—" if self.likeness is None else f"{self.likeness:2}/10"
        quality = "  —  " if self.naturalness is None else f"{self.naturalness}/{self.artifacts}"
        sharp = f"  рез {self.sharpness:6.0f}" if self.sharpness else ""
        return (f"  {self.case:22} {likeness}  кач {quality:5}  техника {mark(self.medium_ok)}"
                f"  буквы {mark(self.letters_ok)}  лишнее {mark(self.absent_ok)}"
                f"  кадр {mark(self.aspect_ok)} {self.size:10}"
                f"{sharp}  {self.seconds:5.1f} c  {self.model or '—'}")


def load_cases(only: Optional[list[str]]) -> list[Case]:
    rows = [json.loads(line) for line in CASES.read_text().splitlines() if line.strip()]
    cases = [Case(id=r["id"], note=r.get("note", ""), body=r["body"], expect=r.get("expect", {}))
             for r in rows]
    if only:
        cases = [c for c in cases if c.id in only]
    return cases


async def guest(client: httpx.AsyncClient) -> dict[str, str]:
    r = await client.post(f"{BASE}/api/auth/guest")
    r.raise_for_status()
    return {"Authorization": f"Bearer {r.json()['session_token']}"}


async def build_profile(client: httpx.AsyncClient, headers: dict, faces: pathlib.Path) -> tuple[str, pathlib.Path]:
    """Завести профиль из папки со снимками. Возвращает id и опорный кадр."""
    photos = sorted(p for p in faces.iterdir()
                    if p.suffix.lower() in {".jpg", ".jpeg", ".png"})[:6]
    if not photos:
        raise SystemExit(f"В {faces} нет снимков — замер без лица бессмысленен")

    media: list[str] = []
    for photo in photos:
        mime = "image/png" if photo.suffix.lower() == ".png" else "image/jpeg"
        r = await client.post(f"{BASE}/api/uploads", headers=headers,
                              files={"file": (photo.name, photo.read_bytes(), mime)})
        r.raise_for_status()
        media.append(r.json()["id"])

    r = await client.post(f"{BASE}/api/profiles", headers=headers,
                          json={"name": "Eval", "media_ids": media})
    r.raise_for_status()
    return r.json()["id"], photos[0]


async def ask_json(system: str, parts: list[dict], *, tries: int = 2) -> Optional[dict]:
    """Спросить судью и разобрать ответ. Одна попытка про запас.

    Судья иногда отвечает не JSON — на двенадцати кадрах это случилось однажды,
    и колонка осталась пустой без всякой причины. Пустая клетка в замере хуже
    неточной: по ней ничего не решишь, а выглядит она как «не проверяли».
    """
    for attempt in range(tries):
        try:
            raw = await gpt._call(
                [{"role": "system", "content": system},
                 {"role": "user", "content": parts}],
                max_tokens=140, temperature=0,
                model=settings.slot_extraction_model or None,
            )
            start, end = raw.index("{"), raw.rindex("}") + 1
            return json.loads(raw[start:end])
        except Exception:  # noqa: BLE001 — вторая попытка, потом сдаёмся
            if attempt + 1 == tries:
                return None
    return None


async def judge_likeness(reference: bytes, frame: bytes) -> tuple[Optional[int], str]:
    """Тот ли человек. Зрением, а не метрикой.

    ArcFace здесь был бы объективнее и не зависел бы от версии судьи, но тянет
    за собой onnxruntime и numpy ради одного числа — и всё равно плохо считает
    сходство на рисованном лице, которого у него в обучении не было. Пока
    судит зрение; когда числу понадобится вес, ArcFace встанет рядом.
    """
    if not settings.openai_enabled:
        return None, "зрение выключено"

    parts = [{"type": "text", "text": "Reference first, generated second."}]
    for data in (reference, frame):
        small = base64.b64encode(gpt.storage_images.preview(data, side=512)).decode()
        parts.append({"type": "image_url",
                      "image_url": {"url": f"data:image/jpeg;base64,{small}"}})
    parsed = await ask_json(_JUDGE_SYSTEM, parts)
    if parsed is None:
        return None, "судья молчит"
    return int(parsed.get("score", 0)), str(parsed.get("reasoning", ""))[:120]


async def judge_absent(frame: bytes, thing: str) -> tuple[Optional[bool], str]:
    """Нет ли в кадре того, чего не просили: шапки, улыбки, лишней вещи."""
    if not settings.openai_enabled:
        return None, "зрение выключено"

    small = base64.b64encode(gpt.storage_images.preview(frame, side=512)).decode()
    parsed = await ask_json(_ABSENT_SYSTEM, [
        {"type": "text", "text": f"Is there {thing} in this picture?"},
        {"type": "image_url", "image_url": {"url": f"data:image/jpeg;base64,{small}"}}])
    if parsed is None:
        return None, "судья молчит"
    return not bool(parsed.get("present")), str(parsed.get("reasoning", ""))[:120]


async def judge_quality(frame: bytes, kind: str = "") -> tuple[Optional[int], Optional[int], str]:
    """Естественность и артефакты — то, чего первому замеру не хватило.

    Вид кадра называем судье прямо. Без этого он ставил ноль мультфильму с
    объяснением «это иллюстрация, а не фотография» — то есть штрафовал кадр за
    то, ради чего его и заказывали.
    """
    if not settings.openai_enabled:
        return None, None, "зрение выключено"

    meant = ("This picture is meant to be an illustration." if kind == "drawn"
             else "This picture is meant to be a photograph." if kind == "photo"
             else "Judge it by the kind of picture it is.")
    small = base64.b64encode(gpt.storage_images.preview(frame, side=512)).decode()
    # Спрашиваем трижды и берём середину.
    #
    # Калибровка показала, что средняя ошибка судьи по качеству невелика, а вот
    # выбросы огромны: тому же кадру он ставит то восемь, то ноль. Одиночная
    # оценка поэтому ничего не значит, а медиана из трёх убирает случайный ноль,
    # не пряча настоящий брак — если кадр действительно плох, ноль придёт
    # дважды. Три вызова зрения стоят доли цента.
    parts = [{"type": "text", "text": meant},
             {"type": "image_url", "image_url": {"url": f"data:image/jpeg;base64,{small}"}}]
    answers = [await ask_json(_QUALITY_SYSTEM, parts, tries=1) for _ in range(3)]
    answers = [a for a in answers if a is not None]
    if not answers:
        return None, None, "судья молчит"

    natural = statistics.median_low(int(a.get("naturalness", 0)) for a in answers)
    artifacts = statistics.median_low(int(a.get("artifacts", 0)) for a in answers)
    spread = max(int(a.get("naturalness", 0)) for a in answers) - \
        min(int(a.get("naturalness", 0)) for a in answers)
    note = str(answers[0].get("reasoning", ""))[:120]
    if spread >= 4:
        # Разброс сам по себе новость: значит, кадр спорный и число по нему
        # решать нельзя.
        note = f"разброс {spread} · {note}"
    return natural, artifacts, note


async def rejudge(folder: pathlib.Path) -> None:
    """Досудить уже снятый прогон: кадры лежат, генерировать заново незачем.

    Замер дорожает генерациями, а не судьями: досудить двадцать четыре кадра
    стоит центы против полутора долларов на повторную съёмку. Значит, новая ось
    добавляется к прошлым прогонам, а не обесценивает их.
    """
    path = folder / "run.json"
    if not path.exists():
        raise SystemExit(f"В {folder} нет run.json")

    summary = json.loads(path.read_text())
    kinds = {c.id: c.expect.get("medium", "") for c in load_cases(None)}
    for case_id, row in summary.items():
        frame_path = folder / f"{case_id}.jpg"
        if not frame_path.exists():
            continue
        row["sharpness"] = sharpness(frame_path.read_bytes())
        natural, artifacts, note = await judge_quality(
            frame_path.read_bytes(), kinds.get(case_id, kinds.get(case_id.rsplit("-", 1)[0], "")))
        row["naturalness"], row["artifacts"] = natural, artifacts
        if note:
            row.setdefault("notes", []).append(note)
        both = [v for v in (natural, artifacts) if v is not None]
        print(f"  {case_id:22} естественность {natural}  артефакты {artifacts}"
              f"  {'· ' + note if note else ''}")
    path.write_text(json.dumps(summary, ensure_ascii=False, indent=2) + "\n")
    print(f"\nДописано в {path}")


LABELS = pathlib.Path("tests/data/frames_labels.jsonl")


def sharpness(data: bytes) -> float:
    """Насколько кадр резкий — арифметикой, а не мнением.

    Дисперсия лапласиана: свёртка, подчёркивающая перепады яркости, и разброс
    того, что получилось. Много резких границ — большое число, мыло — маленькое.

    Числа сравнимы только между кадрами одной просьбы: у ночной улицы и у
    штриховки тушью разное количество границ само по себе, и это не про
    качество. Зато «тот же кадр на другой ступени» она отвечает без судьи,
    бесплатно и одинаково каждый раз — ровно то, чего судье не хватает.
    """
    with Image.open(io.BytesIO(data)) as image:
        grey = image.convert("L")
        grey.thumbnail((1024, 1024), Image.LANCZOS)
        # Смещение на 128, чтобы отрицательные перепады не обрезались нулём.
        edges = grey.filter(ImageFilter.Kernel(
            (3, 3), [0, 1, 0, 1, -4, 1, 0, 1, 0], scale=1, offset=128))
    return round(ImageStat.Stat(edges).var[0], 1)


def calibrate() -> None:
    """Сверить судью с ручной разметкой.

    Без этого шага любое число замера — мнение модели о самой себе. Разметка
    лежит рядом с датасетом: шестнадцать кадров, размеченных глазами, с
    короткой запиской, почему поставлена именно такая оценка.

    Считаем три вещи по отдельности, потому что чинятся они по-разному:
    техника — попадание в вид кадра, тут судья либо прав, либо нет; сходство и
    качество — насколько он щедр или суров против человека.
    """
    if not LABELS.exists():
        raise SystemExit(f"Нет разметки: {LABELS}")

    labels = [json.loads(line) for line in LABELS.read_text().splitlines() if line.strip()]
    runs: dict[str, dict] = {}
    rows = []
    for label in labels:
        folder = RUNS / label["run"]
        if label["run"] not in runs:
            path = folder / "run.json"
            runs[label["run"]] = json.loads(path.read_text()) if path.exists() else {}
        judged = runs[label["run"]].get(label["case"])
        if not judged:
            print(f"  {label['case']:22} нет в прогоне {label['run']}")
            continue
        rows.append((label, judged))

    print(f"{'случай':24} {'вид':>12} {'сходство':>16} {'качество':>16}")
    medium_hits = 0
    likeness_gap, quality_gap = [], []
    harsh, generous = [], []
    for label, judged in rows:
        # Вид кадра судья определяет сам, а разметка говорит, что там на самом
        # деле: сходятся ли — и есть весь вопрос.
        seen = judged.get("medium") or "—"
        agree = seen == label["medium"]
        medium_hits += agree

        line = f"{label['case'][:22]:24} {seen:>6}/{label['medium']:<5}"
        if judged.get("likeness") is not None:
            gap = judged["likeness"] - label["likeness"]
            likeness_gap.append(gap)
            line += f" {judged['likeness']:>6}/{label['likeness']:<2} {gap:+d}   "
        else:
            line += " " * 16
        if judged.get("naturalness") is not None:
            gap = judged["naturalness"] - label["quality"]
            quality_gap.append(gap)
            line += f" {judged['naturalness']:>6}/{label['quality']:<2} {gap:+d}"
            if gap <= -3:
                harsh.append(label["case"])
            elif gap >= 3:
                generous.append(label["case"])
        print(line)

    total = len(rows)
    print(f"\nвид кадра: сошлось {medium_hits} из {total}")
    if likeness_gap:
        print(f"сходство: судья в среднем {sum(likeness_gap) / len(likeness_gap):+.1f} "
              f"к ручной оценке")
    if quality_gap:
        print(f"качество: судья в среднем {sum(quality_gap) / len(quality_gap):+.1f}")
    if harsh:
        print("суров (−3 и хуже):", ", ".join(harsh))
    if generous:
        print("щедр (+3 и выше):", ", ".join(generous))


def read_text(paths: list[pathlib.Path]) -> dict[str, str]:
    """Что написано на кадрах — системным зрением macOS, одним заходом."""
    if not paths or shutil.which("swift") is None or not OCR_SCRIPT.exists():
        return {}
    try:
        done = subprocess.run(["swift", str(OCR_SCRIPT), *[str(p) for p in paths]],
                              capture_output=True, text=True, timeout=300)
    except Exception:  # noqa: BLE001 — чтение не обязано быть доступным
        return {}
    found: dict[str, str] = {}
    for line in done.stdout.splitlines():
        path, _, text = line.partition("\t")
        found[path] = text.strip()
    return found


async def provider_of(generation_id: str) -> tuple[str, str]:
    """Кто и какой моделью сделал кадр.

    Спрашиваем базу, а не список работ: наружу исполнитель не отдаётся —
    человеку он не нужен, а замеру нужен именно он.
    """
    from app.db import models as m
    from app.db import session as dbs

    await dbs.connect()
    async with dbs.get_factory()() as session:
        row = await session.get(m.Generation, generation_id)
        return (row.provider_id or "", row.provider_model or "") if row else ("", "")


async def run_case(client: httpx.AsyncClient, headers: dict, case: Case,
                   profile: str, reference: bytes, out: pathlib.Path) -> Outcome:
    result = Outcome(case=case.id, expect=case.expect)
    body = {"type": "image", "from_chat": False, "post_prompt": False,
            "profile_id": profile, **case.body}

    started = time.monotonic()
    response = await client.post(f"{BASE}/api/generate", headers=headers, json=body)
    result.seconds = time.monotonic() - started
    if response.status_code != 200:
        result.ok = False
        result.notes.append(f"{response.status_code}: {response.text[:120]}")
        return result

    payload = response.json()
    frame = (await client.get(f"{BASE}{payload['url']}", headers=headers)).content
    path = out / f"{case.id}.jpg"
    path.write_bytes(frame)
    result.path = str(path)

    # Чем и как это сделано — из записи о генерации, а не из догадок.
    result.provider, result.model = await provider_of(payload["id"])

    expect = case.expect
    if expect.get("person"):
        result.likeness, note = await judge_likeness(reference, frame)
        if note:
            result.notes.append(note)

    result.sharpness = sharpness(frame)
    result.naturalness, result.artifacts, note = await judge_quality(
        frame, expect.get("medium", ""))
    if note:
        result.notes.append(note)

    if expect.get("medium"):
        photographic = await gpt.looks_photographic(frame)
        result.medium = "photo" if photographic else "drawn"
        result.medium_ok = result.medium == expect["medium"]

    if absent := expect.get("absent"):
        result.absent_ok, note = await judge_absent(frame, absent)
        if note:
            result.notes.append(note)

    # Форма кадра — не «просили и ладно»: часть моделей не знает половины
    # пропорций, и мы подменяем значение на ближайшее. Что вышло на самом деле,
    # видно только по файлу.
    with Image.open(path) as image:
        width, height = image.size
    result.size = f"{width}x{height}"
    if wanted_aspect := (case.body.get("aspect") or expect.get("aspect")):
        left, _, right = wanted_aspect.partition(":")
        target = float(left) / float(right)
        result.aspect_ok = abs(width / height - target) / target < 0.08

    if wanted := expect.get("provider"):
        if result.provider and result.provider != wanted:
            result.notes.append(f"сделал {result.provider}, ждали {wanted}")

    return result


def check_letters(results: list[Outcome]) -> None:
    """Буквы читаем скопом: один запуск Vision на все кадры сразу."""
    paths = [pathlib.Path(r.path) for r in results if r.path]
    text = read_text(paths)
    if not text:
        return
    for result in results:
        expect = result.expect
        found = text.get(result.path, "")
        result.letters = found[:40]
        if wanted := expect.get("letters"):
            result.letters_ok = wanted.lower() in found.lower()
        elif expect.get("no_letters"):
            # Пустая строка — не единственный годный ответ: OCR ловит и подписи
            # на вывесках в кадре. Считаем провалом только заметный текст.
            result.letters_ok = len(found.replace(" ", "")) < 4


def compare(now: dict, out: pathlib.Path) -> Optional[str]:
    """Сравнить с прошлым прогоном: смысл замера в сдвиге, а не в абсолюте."""
    previous = sorted(p for p in RUNS.iterdir() if p.is_dir() and p != out)
    if not previous:
        return None
    old_path = previous[-1] / "run.json"
    if not old_path.exists():
        return None
    old = json.loads(old_path.read_text())
    lines = [f"Против прогона {previous[-1].name}:"]
    for case_id, current in now.items():
        was = old.get(case_id)
        if not was:
            continue
        moved = []
        if was.get("likeness") is not None and current.get("likeness") is not None:
            delta = current["likeness"] - was["likeness"]
            if abs(delta) >= 2:
                moved.append(f"сходство {was['likeness']}→{current['likeness']}")
        for key, label in (("medium_ok", "техника"), ("letters_ok", "буквы"),
                           ("absent_ok", "лишнее"), ("aspect_ok", "кадр")):
            if was.get(key) != current.get(key) and current.get(key) is not None:
                moved.append(f"{label} {'✓' if current[key] else '✗'}")
        if moved:
            lines.append(f"  {case_id:22} {', '.join(moved)}")
    return "\n".join(lines) if len(lines) > 1 else "Против прошлого прогона — без сдвигов."


async def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--faces", type=pathlib.Path,
                        help="папка со снимками человека, из которых собрать профиль")
    parser.add_argument("--cases", help="через запятую: только эти случаи")
    parser.add_argument("--repeats", type=int, default=1,
                        help="сколько раз прогнать каждый случай")
    parser.add_argument("--rejudge", type=pathlib.Path,
                        help="досудить уже снятый прогон, ничего не генерируя")
    parser.add_argument("--calibrate", action="store_true",
                        help="сверить судью с ручной разметкой")
    args = parser.parse_args()

    if args.calibrate:
        calibrate()
        return

    if args.rejudge:
        await rejudge(args.rejudge)
        return

    if not args.faces:
        raise SystemExit("Нужен --faces: замер без лица бессмысленен")

    cases = load_cases(args.cases.split(",") if args.cases else None)
    if not cases:
        raise SystemExit("Не нашёл ни одного случая")

    stamp = time.strftime("%Y-%m-%d-%H%M")
    out = RUNS / stamp
    out.mkdir(parents=True, exist_ok=True)

    async with httpx.AsyncClient(timeout=600) as client:
        try:
            headers = await guest(client)
        except Exception as exc:  # noqa: BLE001
            raise SystemExit(f"Сервер на {BASE} не отвечает ({type(exc).__name__}). "
                             "Замер ходит по HTTP: подними ./run-local.sh") from exc

        profile, reference_path = await build_profile(client, headers, args.faces)
        reference = reference_path.read_bytes()
        print(f"Профиль {profile}, опорный кадр {reference_path.name}\n")

        results: list[Outcome] = []
        for attempt in range(args.repeats):
            for case in cases:
                suffix = f"-{attempt + 1}" if args.repeats > 1 else ""
                one = await run_case(client, headers,
                                     Case(case.id + suffix, case.note, case.body, case.expect),
                                     profile, reference, out)
                results.append(one)
                print(f"  {one.case:22} сделан за {one.seconds:5.1f} c")

    check_letters(results)

    print("\nЧто получилось:")
    for result in results:
        print(result.as_row())

    print("\nБуквы и оговорки:")
    for result in results:
        if result.letters or result.notes:
            print(f"  {result.case:22} {result.letters or '—':42} {'; '.join(result.notes)}")

    summary = {r.case: {"likeness": r.likeness, "medium": r.medium,
                        "medium_ok": r.medium_ok, "letters_ok": r.letters_ok,
                        "absent_ok": r.absent_ok, "aspect_ok": r.aspect_ok,
                        "naturalness": r.naturalness, "artifacts": r.artifacts,
                        "sharpness": r.sharpness,
                        "size": r.size, "seconds": round(r.seconds, 1),
                        "provider": r.provider, "model": r.model,
                        "notes": r.notes} for r in results}
    (out / "run.json").write_text(json.dumps(summary, ensure_ascii=False, indent=2) + "\n")

    if (moved := compare(summary, out)):
        print("\n" + moved)
    (out / ".gitignore").write_text("*.jpg\n")
    print(f"\nКадры и числа: {out}")
    print("Кадры не в git: смотреть их — глазами и сейчас, в истории нужны числа.")


if __name__ == "__main__":
    asyncio.run(main())
